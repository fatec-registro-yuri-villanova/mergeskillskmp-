fun Route.progressRoutes(supabase: SupabaseClient) {
    route("/progress") {
        post("/submit") {
            try {
                val request = call.receive<SubmitAnswerRequest>()
                
                // 1. Get the Question
                val question = supabase.from("questions").select {
                    filter { eq("id", request.questionId) }
                }.decodeSingleOrNull<Question>()

                if (question == null) {
                    call.respond(
                        HttpStatusCode.NotFound,
                        ApiError(code = "QUESTION_NOT_FOUND", message = "Question top submit not found")
                    )
                    return@post
                }

                val isCorrect = request.selectedOption == question.correctAnswer
                val nowStr = Instant.now().toString()

                // 2. Save the Attempt (Wait, first we must make sure QuestionAttempt can be inserted without ID if it is autogenerated, or use an InsertQuestionAttempt DTO)
                // Let's use map to insert
                supabase.from("question_attempts").insert(
                    mapOf(
                        "user_id" to request.userId,
                        "question_id" to request.questionId,
                        "selected_option" to request.selectedOption,
                        "is_correct" to isCorrect,
                        "timestamp" to nowStr
                    )
                )

                // 3. Check if all questions of the lesson are answered
                val lessonId = question.lessonId ?: return@post call.respond(
                    HttpStatusCode.BadRequest,
                    ApiError(code = "INVALID_QUESTION", message = "Question is not bound to a lesson")
                )

                val allQuestions = supabase.from("questions").select {
                    filter { eq("lesson_id", lessonId) }
                }.decodeList<Question>()

                val questionIds = allQuestions.mapNotNull { it.id }
                
                val userAttempts = supabase.from("question_attempts").select {
                    filter { 
                        eq("user_id", request.userId)
                        isIn("question_id", questionIds)
                    }
                }.decodeList<QuestionAttempt>()

                val answeredQuestionIds = userAttempts.mapNotNull { it.questionId }.toSet()
                val allAnswered = allQuestions.all { q -> answeredQuestionIds.contains(q.id) }

                var finalStreak: Int? = null
                var finalFreezes: Int? = null

                if (allAnswered && allQuestions.isNotEmpty()) {
                    // Check if already completed
                    val existingProgress = supabase.from("lesson_progress").select {
                        filter {
                            eq("user_id", request.userId)
                            eq("lesson_id", lessonId)
                        }
                    }.decodeSingleOrNull<LessonProgress>()

                    if (existingProgress == null || existingProgress.isCompleted != true) {
                        // Mark as completed
                        if (existingProgress == null) {
                            supabase.from("lesson_progress").insert(
                                mapOf(
                                    "user_id" to request.userId,
                                    "lesson_id" to lessonId,
                                    "is_completed" to true,
                                    "completed_at" to nowStr
                                )
                            )
                        } else {
                            supabase.from("lesson_progress").update(
                                {
                                    set("is_completed", true)
                                    set("completed_at", nowStr)
                                }
                            ) {
                                filter {
                                    eq("user_id", request.userId)
                                    eq("lesson_id", lessonId)
                                }
                            }
                        }

                        // Update streak
                        val timezone = call.request.header("X-Timezone") ?: "UTC"
                        val (streak, freezes) = updateStreakOnActivity(supabase, request.userId, timezone)
                        finalStreak = streak
                        finalFreezes = freezes
                    }
                }

                if (finalStreak == null) {
                    val user = supabase.from("users").select {
                        filter { eq("id", request.userId) }
                    }.decodeSingleOrNull<User>()
                    finalStreak = user?.streakCount
                    finalFreezes = user?.streakFreezes
                }

                call.respond(
                    SubmitAnswerResponse(
                        isCorrect = isCorrect,
                        correctAnswer = question.correctAnswer,
                        message = if (isCorrect) "Resposta correta!" else "Resposta incorreta.",
                        newStreak = finalStreak,
                        streakFreezes = finalFreezes
                    )
                )

            } catch (e: Exception) {
                call.respond(
                    HttpStatusCode.InternalServerError,
                    ApiError(code = "SUBMISSION_FAILED", message = "Failed to submit answer: ${e.message}")
                )
            }
        }

        post("/reset") {
            try {
                val request = call.receive<ResetProgressRequest>()
                
                val allQuestions = supabase.from("questions").select {
                    filter { eq("lesson_id", request.lessonId) }
                }.decodeList<Question>()
                
                val questionIds = allQuestions.mapNotNull { it.id }

                if (questionIds.isNotEmpty()) {
                    supabase.from("question_attempts").delete {
                        filter { 
                            eq("user_id", request.userId)
                            isIn("question_id", questionIds)
                        }
                    }
                }

                supabase.from("lesson_progress").delete {
                    filter {
                        eq("user_id", request.userId)
                        eq("lesson_id", request.lessonId)
                    }
                }

                call.respond(mapOf("message" to "Progresso resetado com sucesso"))
            } catch (e: Exception) {
                call.respond(
                    HttpStatusCode.InternalServerError,
                    ApiError(code = "RESET_FAILED", message = "Failed to reset progress: ${e.message}")
                )
            }
        }

        get("/history/{userId}") {
            try {
                val userId = call.parameters["userId"]?.toIntOrNull()
                if (userId == null) {
                    call.respond(
                        HttpStatusCode.BadRequest,
                        ApiError(code = "INVALID_USER_ID", message = "User ID must be an integer")
                    )
                    return@get
                }

                val completed = supabase.from("lesson_progress").select {
                    filter {
                        eq("user_id", userId)
                        eq("is_completed", true)
                    }
                }.decodeList<LessonProgress>()

                call.respond(ProgressHistoryResponse(completedLessons = completed))
            } catch (e: Exception) {
                call.respond(
                    HttpStatusCode.InternalServerError,
                    ApiError(code = "HISTORY_FETCH_FAILED", message = "Failed to fetch history: ${e.message}")
                )
            }
        }
    }
}

suspend fun updateStreakOnActivity(supabase: SupabaseClient, userId: Int, timezoneId: String): Pair<Int, Int> {
    val user = supabase.from("users").select {
        filter { eq("id", userId) }
    }.decodeSingleOrNull<User>() ?: return Pair(0, 0)

    val zoneId = try {
        ZoneId.of(timezoneId)
    } catch (e: Exception) {
        ZoneId.of("UTC")
    }

    val now = ZonedDateTime.now(zoneId)
    val today = now.toLocalDate()

    val lastActivity = user.lastActivityAt?.let {
        try {
            Instant.parse(it).atZone(zoneId).toLocalDate()
        } catch (e: Exception) {
            null
        }
    }

    var newStreak = user.streakCount ?: 0
    var newFreezes = user.streakFreezes ?: 0
    val longestStreak = user.longestStreak ?: 0

    if (lastActivity == null) {
        newStreak = 1
    } else {
        if (lastActivity.isEqual(today)) {
            if (newStreak == 0) {
                newStreak = 1
            }
        } else if (lastActivity.plusDays(1).isEqual(today)) {
            newStreak += 1
        } else {
            val daysMissed = ChronoUnit.DAYS.between(lastActivity, today)
            
            if (daysMissed > 1) {
                if (newFreezes > 0) {
                    newFreezes -= 1
                    newStreak += 1
                } else {
                    newStreak = 1
                }
            }
        }
    }

    val newLongest = maxOf(longestStreak, newStreak)
    val newActivityTime = Instant.now().toString()

    supabase.from("users").update(
        {
            set("streak_count", newStreak)
            set("streak_freezes", newFreezes)
            set("longest_streak", newLongest)
            set("last_activity_at", newActivityTime)
        }
    ) {
        filter { eq("id", userId) }
    }

    return Pair(newStreak, newFreezes)
}
